import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const base = process.env.DASHBOARD_URL || 'http://127.0.0.1:5173';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--disable-gpu', '--renderer-process-limit=1'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, timezoneId: 'Europe/London', locale: 'en-GB' });
const page = await context.newPage();
const errors = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
async function ready() { await page.locator('.player-stat').first().waitFor(); await page.waitForFunction(() => !document.querySelector('[aria-busy="true"]')); await page.evaluate(() => document.fonts.ready); }
try {
  await page.goto(`${base}/teams/12?season=20262027`);
  await page.getByRole('link', { name: 'View Sebastian Aho player page', exact: true }).click();
  await ready();
  assert.match(page.url(), /\/players\/8478427/);
  assert.equal(await page.locator('h1').textContent(), 'Sebastian Aho');
  assert.equal(await page.locator('.player-stat').count(), 4);
  assert.equal(await page.locator('.player-workspace').evaluate(el => getComputedStyle(el).getPropertyValue('--team-primary').trim()), '#CD001A');
  assert.equal(await page.locator('.player-portrait img').getAttribute('src'), 'https://assets.nhle.com/mugs/nhl/20262027/CAR/8478427.png');
  assert.match(await page.locator('.history-chart figcaption').textContent(), /One saved snapshot/);
  await page.screenshot({ path: 'test-results/player-page.png', fullPage: true });
  await page.reload(); await ready();
  checks.push('Player links, direct reload, headshot, team styling, four stats/interval cards and honest single-snapshot chart.');
  await page.getByLabel('Season', { exact: true }).selectOption('20252026'); await ready();
  assert.ok(await page.locator('.history-dates button').count() > 1);
  const first = await page.locator('.history-dates button').first().textContent();
  await page.locator('.history-dates button').first().click(); await ready();
  assert.ok((await page.locator('.player-hero').textContent()).includes(first));
  await page.getByText('View labelled graph data', { exact: true }).click();
  assert.equal(await page.locator('.history-chart tbody tr').count(), await page.locator('.history-dates button').count());
  await page.getByLabel('Graph statistic', { exact: true }).selectOption('goals'); await ready();
  await page.getByLabel('Prediction interval', { exact: true }).selectOption('0.95'); await ready();
  assert.match(await page.locator('.history-chart svg').getAttribute('aria-label'), /Goals/);
  await page.getByLabel('Projection model', { exact: true }).selectOption('pace'); await ready();
  await page.reload(); await ready();
  assert.equal(await page.getByLabel('Graph statistic', { exact: true }).inputValue(), 'goals');
  assert.equal(await page.getByLabel('Prediction interval', { exact: true }).inputValue(), '0.95');
  assert.equal(await page.getByLabel('Projection model', { exact: true }).inputValue(), 'pace');
  await page.screenshot({ path: 'test-results/player-history.png', fullPage: true });
  checks.push('Historical multi-snapshot graph, date selection, exact data table, statistic, interval and model controls.');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.ok(await page.locator('.history-scroll').evaluate(el => el.scrollWidth > el.clientWidth));
  await page.screenshot({ path: 'test-results/player-mobile.png', fullPage: true });
  await page.goto(`${base}/players/8478427?season=20212022`); await ready();
  assert.match(await page.locator('.player-stat-band').first().textContent(), /Unavailable/);
  await page.goto(`${base}/players/999999999?season=20262027`);
  await page.getByRole('alert').waitFor();
  checks.push('390px mobile layout, insufficient historical calibration and missing player states.');
  await page.goto(base); await page.locator('.game-card time').first().waitFor();
  assert.match(await page.locator('#games .section-heading p').textContent(), /Europe\/London/);
  const clock = page.locator('.game-card time').first();
  const instant = await clock.getAttribute('datetime');
  assert.equal(await clock.textContent(), await page.evaluate(iso => new Intl.DateTimeFormat(undefined, { weekday: 'short', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit', timeZone: 'Europe/London', timeZoneName: 'short' }).format(new Date(iso)), instant));
  checks.push('Game clock uses the browser timezone and a semantic UTC datetime.');
  assert.deepEqual(errors, []);
  await writeFile('test-results/player-pages.json', JSON.stringify({ checks, errors }, null, 2));
  console.log(`PASS: ${checks.length} player-page browser check groups`);
} finally { await browser.close(); }
